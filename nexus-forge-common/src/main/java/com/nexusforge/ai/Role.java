package com.nexusforge.ai;

/**
 * 角色枚举类
 * <p>
 * 用于定义AI对话系统中的参与者角色，遵循OpenAI API的角色规范。
 * 每个角色在对话中承担不同的功能和交互模式。
 * </p>
 */
public enum Role {
    /**
     * 系统角色
     * <p>
     * 用于设置AI助手的顶层指令和行为约束。
     * 系统消息通常在对话开始时设置，定义AI的角色定位、回复风格和限制条件。
     * 例如："你是一个乐于助人的Java编程专家"。
     * </p>
     * <p>
     * <b>使用场景：</b> 在对话开始时初始化AI的行为准则
     * </p>
     */
    SYSTEM,

    /**
     * 用户角色
     * <p>
     * 代表最终用户发出的消息，即向AI提出的问题、请求或指令。
     * 用户消息是对话的驱动力量，AI需要根据用户输入生成响应。
     * </p>
     * <p>
     * <b>使用场景：</b> 用户提问、发送指令、提供上下文信息
     * </p>
     */
    USER,

    /**
     * 助手角色
     * <p>
     * 代表AI助手生成的回复消息。
     * 助手消息是对用户输入的响应，通常包含AI的理解、分析和建议。
     * 在多轮对话中，助手消息会累积形成对话历史。
     * </p>
     * <p>
     * <b>使用场景：</b> AI回复用户问题、提供代码示例、给出建议
     * </p>
     */
    ASSISTANT,

    /**
     * 工具角色
     * <p>
     * 用于表示AI调用外部工具或功能后返回的结果。
     * 当AI需要执行特定操作（如查询数据库、调用API、计算等）时，
     * 工具消息可以携带这些操作的结果供AI后续处理。
     * </p>
     * <p>
     * <b>使用场景：</b> 函数调用结果、外部系统响应、工具执行反馈
     * </p>
     * <p>
     * <b>注意：</b> 这是OpenAI较新支持的角色类型，用于增强AI的扩展能力
     * </p>
     */
    TOOL
}